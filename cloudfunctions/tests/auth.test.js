'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');

const { authenticateUpload } = require('../shared/auth');
const { MAX_BODY_BYTES } = require('../shared/config');
const { PatrolCloudError } = require('../shared/errors');
const {
  TEST_DEVICE_ID,
  TEST_NOW_MS,
  TEST_SECRET,
  signedEvent,
  validPayload,
} = require('./helpers');

const config = { deviceId: TEST_DEVICE_ID, uploadSecret: TEST_SECRET };

test('authenticates the exact sidecar HMAC contract', () => {
  const event = signedEvent(validPayload());
  const result = authenticateUpload(event, config, TEST_NOW_MS);
  assert.equal(result.deviceId, TEST_DEVICE_ID);
  assert.equal(result.nonce, 'nonce-0000000000000001');
  assert.equal(result.requestTimestampEpochS, 1_700_000_000);
  assert.equal(result.rawBody, event.body);
  assert.match(result.bodySha256, /^[0-9a-f]{64}$/);
});

test('matches the fixed signature vector generated by the Python sidecar', () => {
  const rawBody = '{"schema_version":"patrol-dashboard/v1"}';
  const event = {
    httpMethod: 'POST',
    body: rawBody,
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      'X-Patrol-Signature-Version': 'patrol-hmac-sha256-v1',
      'X-Patrol-Device-Id': 'macmini-m4',
      'X-Patrol-Timestamp': '1788192000',
      'X-Patrol-Nonce': '0123456789abcdef0123456789abcdef',
      'X-Patrol-Body-SHA256': '921fedb9b01a330e7329725282b563b9b7e57e114b635c0c5be3344f8762a2ed',
      'X-Patrol-Signature': 'f50f89ddb694f9ef76eb5ea6572dba31774918c1ff9279532b2088e6264b8b4a',
    },
  };
  const result = authenticateUpload(
    event,
    { deviceId: 'macmini-m4', uploadSecret: 's'.repeat(32) },
    1_788_192_000_000,
  );
  assert.equal(result.rawBody, rawBody);
});

test('header names are case insensitive', () => {
  const event = signedEvent(validPayload());
  event.header = Object.fromEntries(
    Object.entries(event.headers).map(([key, value]) => [key.toLowerCase(), value]),
  );
  delete event.headers;
  assert.equal(authenticateUpload(event, config, TEST_NOW_MS).deviceId, TEST_DEVICE_ID);
});

test('rejects digest and signature tampering', () => {
  const badDigest = signedEvent(validPayload(), { bodySha256: '0'.repeat(64) });
  assert.throws(
    () => authenticateUpload(badDigest, config, TEST_NOW_MS),
    (error) => error instanceof PatrolCloudError && error.code === 'BODY_DIGEST_MISMATCH',
  );

  const badSignature = signedEvent(validPayload(), { signature: 'f'.repeat(64) });
  assert.throws(
    () => authenticateUpload(badSignature, config, TEST_NOW_MS),
    (error) => error instanceof PatrolCloudError && error.code === 'SIGNATURE_MISMATCH',
  );
});

test('rejects stale timestamps, short nonces, and a different device', () => {
  assert.throws(
    () => authenticateUpload(
      signedEvent(validPayload(), { timestamp: '1699999000' }),
      config,
      TEST_NOW_MS,
    ),
    (error) => error.code === 'STALE_TIMESTAMP',
  );
  assert.throws(
    () => authenticateUpload(
      signedEvent(validPayload(), { nonce: 'too-short' }),
      config,
      TEST_NOW_MS,
    ),
    (error) => error.code === 'INVALID_NONCE',
  );
  assert.throws(
    () => authenticateUpload(
      signedEvent(validPayload(), { deviceId: 'another-device' }),
      config,
      TEST_NOW_MS,
    ),
    (error) => error.code === 'DEVICE_NOT_ALLOWED',
  );
});

test('enforces POST and the 128 KiB body limit before JSON processing', () => {
  assert.throws(
    () => authenticateUpload(signedEvent(validPayload(), { method: 'GET' }), config, TEST_NOW_MS),
    (error) => error.code === 'METHOD_NOT_ALLOWED' && error.statusCode === 405,
  );
  const oversized = 'x'.repeat(MAX_BODY_BYTES + 1);
  assert.throws(
    () => authenticateUpload(signedEvent(oversized), config, TEST_NOW_MS),
    (error) => error.code === 'BODY_TOO_LARGE' && error.statusCode === 413,
  );
});

test('requires an application/json content type', () => {
  const event = signedEvent(validPayload());
  delete event.headers['Content-Type'];
  assert.throws(
    () => authenticateUpload(event, config, TEST_NOW_MS),
    (error) => error.code === 'UNSUPPORTED_MEDIA_TYPE' && error.statusCode === 415,
  );
});

test('fails closed when the cloud secret is absent or too short', () => {
  assert.throws(
    () => authenticateUpload(signedEvent(validPayload()), { deviceId: TEST_DEVICE_ID }, TEST_NOW_MS),
    /PATROL_RELAY_UPLOAD_SECRET/,
  );
});
